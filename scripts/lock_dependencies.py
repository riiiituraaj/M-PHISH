"""Generate exact transitive pins from the verified Python environment."""
from importlib.metadata import distribution, version
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

runtime=['fastapi','uvicorn','pydantic','httpx','python-dotenv','SQLAlchemy','alembic','numpy','tldextract','pwdlib','argon2-cffi','psycopg','psycopg-binary','redis','rq','reportlab']
evaluation=['scikit-learn','xgboost']
development=['pytest','ruff','pip-audit','PyMuPDF','playwright']
def closure(roots):
    pending=list(roots)
    packages={}
    while pending:
        name=canonicalize_name(pending.pop())
        if name in packages:
            continue
        installed=distribution(name)
        packages[name]=installed.version
        for requirement in installed.requires or []:
            req=Requirement(requirement)
            if req.marker is None or req.marker.evaluate():
                pending.append(req.name)
    return '\n'.join(name+'=='+value for name,value in sorted(packages.items()))+'\n'

Path('backend/requirements.lock').write_text(closure(runtime),encoding='utf-8')
Path('backend/requirements-evaluation.lock').write_text(closure(runtime+evaluation),encoding='utf-8')
Path('backend/requirements-dev.lock').write_text(closure(runtime+evaluation+development),encoding='utf-8')
Path('backend/requirements.txt').write_text('# Runtime transitive pins, generated by scripts/lock_dependencies.py\n-r requirements.lock\n',encoding='utf-8')
